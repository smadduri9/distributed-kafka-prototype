package com.kafkads.cluster;

import com.kafkads.broker.Main;
import com.kafkads.client.Consumer;
import com.kafkads.client.ConsumerRecord;
import com.kafkads.client.Producer;
import com.kafkads.client.UncertainWriteException;
import com.kafkads.protocol.Acks;
import com.kafkads.protocol.messages.MetadataResponse;
import com.kafkads.testutil.TestBrokers;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicBoolean;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Three brokers as three separate operating-system processes, killed with SIGKILL
 * ({@link Process#destroyForcibly()}), so nothing in the dying broker gets to run a
 * shutdown hook, flush a buffer or close a socket politely.
 *
 * <p>What this shows: acknowledged records survive the abrupt death of the leader
 * process, the cluster keeps committing with one broker gone, and the dead broker
 * converges after a restart without replaying anything twice.
 *
 * <p>What it does not show: behaviour under power loss or kernel crash. SIGKILL kills
 * the process but the operating system still writes out its page cache, so this test
 * says nothing about data that was written but not yet fsynced reaching the disk.
 */
class MultiProcessFailoverTest {

    private static final int BASE_PORT = 20500;
    private static final int PARTITIONS = 3;

    @TempDir
    Path tmp;

    private final Map<Integer, Process> processes = new HashMap<>();
    private TestBrokers layout;

    @AfterEach
    void killEverything() throws InterruptedException {
        for (Process p : processes.values()) {
            p.destroyForcibly();
            p.waitFor(10, TimeUnit.SECONDS);
        }
    }

    private void startProcess(int id) throws IOException {
        Path config = tmp.resolve("broker-" + id + ".properties");
        Properties props = layout.properties(id);
        try (OutputStream out = Files.newOutputStream(config)) {
            props.store(out, "generated by MultiProcessFailoverTest");
        }
        String java = Path.of(System.getProperty("java.home"), "bin", "java").toString();
        ProcessBuilder pb = new ProcessBuilder(java, "-cp", System.getProperty("java.class.path"),
                Main.class.getName(), config.toString());
        pb.redirectErrorStream(true);
        pb.redirectOutput(ProcessBuilder.Redirect.appendTo(tmp.resolve("broker-" + id + ".out").toFile()));
        processes.put(id, pb.start());
    }

    /** SIGKILL, then wait until the process is really gone. */
    private void kill(int id) throws InterruptedException {
        Process p = processes.remove(id);
        long pid = p.pid();
        p.destroyForcibly();
        assertTrue(p.waitFor(10, TimeUnit.SECONDS), "process " + pid + " did not die");
        assertNotEquals(0, p.exitValue(), "a killed process does not exit cleanly");
    }

    private MetadataResponse status(Consumer consumer, int id) {
        return consumer.metadataFrom("127.0.0.1:" + layout.port(id));
    }

    private boolean reachable(Consumer consumer, int id) {
        try {
            status(consumer, id);
            return true;
        } catch (RuntimeException e) {
            return false;
        }
    }

    /** The broker that reports itself as leader of the partition, or -1. */
    private int leaderOf(Consumer consumer, int partition) {
        for (int id : processes.keySet()) {
            try {
                MetadataResponse.PartitionInfo info = status(consumer, id).partitions().get(partition);
                if (info.leader() == id) {
                    return id;
                }
            } catch (RuntimeException e) {
                // broker not answering; try the next
            }
        }
        return -1;
    }

    private static List<String> strings(List<ConsumerRecord> records) {
        List<String> out = new ArrayList<>();
        for (ConsumerRecord r : records) {
            out.add(new String(r.value(), StandardCharsets.UTF_8));
        }
        return out;
    }

    @Test
    void acknowledgedRecordsSurviveSigkillOfTheLeaderProcess() throws Exception {
        layout = new TestBrokers(tmp.resolve("data"), BASE_PORT, 3, PARTITIONS, 3);
        for (int id = 1; id <= 3; id++) {
            startProcess(id);
        }
        Map<Integer, List<String>> acknowledged = new HashMap<>();
        for (int p = 0; p < PARTITIONS; p++) {
            acknowledged.put(p, new ArrayList<>());
        }
        Set<String> uncertain = ConcurrentHashMap.newKeySet();

        try (Producer producer = new Producer(layout.bootstrap());
             Consumer consumer = new Consumer(layout.bootstrap())) {
            for (int id = 1; id <= 3; id++) {
                final int broker = id;
                assertTrue(TestBrokers.await(() -> reachable(consumer, broker), 20_000),
                        "broker process " + id + " did not start; see " + tmp.resolve("broker-" + id + ".out"));
            }

            // 1. Committed writes to every partition.
            for (int p = 0; p < PARTITIONS; p++) {
                producer.send(p, TestBrokers.values("p" + p + "-before-", 0, 40), Acks.QUORUM);
                acknowledged.get(p).addAll(TestBrokers.strings("p" + p + "-before-", 0, 40));
            }

            // 2. A writer keeps producing to partition 0 while its leader is killed.
            int victim = leaderOf(consumer, 0);
            assertTrue(victim > 0, "partition 0 has a leader");
            List<String> liveAcknowledged = new ArrayList<>();
            AtomicBoolean stop = new AtomicBoolean();
            Thread writer = new Thread(() -> {
                try (Producer live = new Producer(layout.bootstrap())) {
                    for (int i = 0; !stop.get(); i++) {
                        String value = "p0-live-" + i;
                        try {
                            live.send(0, List.of(value.getBytes(StandardCharsets.UTF_8)), Acks.QUORUM);
                            liveAcknowledged.add(value);
                        } catch (UncertainWriteException e) {
                            uncertain.add(value); // may or may not be stored; must not be stored twice
                        } catch (RuntimeException e) {
                            // rejected: definitely not stored
                        }
                    }
                }
            }, "live-writer");
            writer.start();
            Thread.sleep(300);
            kill(victim); // SIGKILL the leader process mid-stream
            Thread.sleep(1500);
            stop.set(true);
            writer.join(30_000);
            assertFalse(writer.isAlive());
            acknowledged.get(0).addAll(liveAcknowledged);
            assertTrue(liveAcknowledged.size() > 5, "the writer made progress around the failover");
            System.out.println("[MultiProcessFailoverTest] killed leader broker " + victim + " (SIGKILL); live writer: "
                    + liveAcknowledged.size() + " acknowledged, " + uncertain.size() + " uncertain");

            // 3. Every acknowledged record is readable, now from leaders among the two survivors.
            for (int p = 0; p < PARTITIONS; p++) {
                assertNotEquals(victim, leaderOf(consumer, p));
                assertContainsExactlyOnce(strings(consumer.readAll(p, 0)), acknowledged.get(p), uncertain, p);
            }

            // 4. Committed writes continue with one broker process gone.
            for (int p = 0; p < PARTITIONS; p++) {
                producer.send(p, TestBrokers.values("p" + p + "-degraded-", 0, 30), Acks.QUORUM);
                acknowledged.get(p).addAll(TestBrokers.strings("p" + p + "-degraded-", 0, 30));
            }

            // 5. Restart the killed broker on its old data directory and wait for it to catch up.
            startProcess(victim);
            assertTrue(TestBrokers.await(() -> reachable(consumer, victim), 20_000));
            for (int p = 0; p < PARTITIONS; p++) {
                final int partition = p;
                assertTrue(TestBrokers.await(() -> {
                    int leader = leaderOf(consumer, partition);
                    if (leader < 0) {
                        return false;
                    }
                    MetadataResponse.PartitionInfo theirs = status(consumer, leader).partitions().get(partition);
                    MetadataResponse.PartitionInfo mine = status(consumer, victim).partitions().get(partition);
                    return mine.logEndOffset() == theirs.logEndOffset()
                            && mine.highWatermark() == theirs.highWatermark()
                            && theirs.highWatermark() == theirs.logEndOffset();
                }, 20_000), "restarted broker did not converge on partition " + p);
            }

            // 6. With all three back, a write that needs every replica succeeds.
            for (int p = 0; p < PARTITIONS; p++) {
                producer.send(p, TestBrokers.values("p" + p + "-all-", 0, 5), Acks.ALL);
                acknowledged.get(p).addAll(TestBrokers.strings("p" + p + "-all-", 0, 5));
                assertContainsExactlyOnce(strings(consumer.readAll(p, 0)), acknowledged.get(p), uncertain, p);
            }
        }

        // 7. Kill everything abruptly and inspect each broker's files directly.
        for (int id : new ArrayList<>(processes.keySet())) {
            kill(id);
        }
        for (int id = 1; id <= 3; id++) {
            for (int p = 0; p < PARTITIONS; p++) {
                List<String> onDisk = TestBrokers.dataOnDisk(layout.logDir(id, p));
                assertContainsExactlyOnce(onDisk, acknowledged.get(p), uncertain, p);
                assertEquals(TestBrokers.dataOnDisk(layout.logDir(1, p)), onDisk,
                        "broker " + id + " partition " + p + " has the same records in the same order as broker 1");
            }
        }
    }

    /**
     * Every acknowledged record appears exactly once and in acknowledgement order; a record
     * whose outcome was uncertain appears at most once; nothing else appears.
     */
    private static void assertContainsExactlyOnce(List<String> actual, List<String> acknowledged,
                                                  Set<String> uncertain, int partition) {
        Map<String, Integer> counts = new HashMap<>();
        for (String s : actual) {
            counts.merge(s, 1, Integer::sum);
        }
        for (String s : acknowledged) {
            assertEquals(1, counts.getOrDefault(s, 0), "partition " + partition + ": acknowledged record " + s);
        }
        List<String> withoutUncertain = new ArrayList<>(actual);
        withoutUncertain.removeAll(uncertain);
        assertEquals(acknowledged, withoutUncertain, "partition " + partition + ": order and content");
        for (String s : actual) {
            assertTrue(counts.get(s) == 1, "partition " + partition + ": record stored twice: " + s);
        }
    }
}
